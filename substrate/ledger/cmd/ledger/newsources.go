// lookupSource returns the source sources.yaml names id.
func lookupSource(dir, id string) (*ledger.Source, error) {
	sources, err := ledger.LoadSources(dir)
	if err != nil {
		return nil, err
	}
	src := sources.Lookup(id)
	if src == nil {
		return nil, fmt.Errorf("%s names no %q source", ledger.FileSources, id)
	}
	return src, nil
}

// unitFiles encodes a source's units and report as the files the ledger commits for it.
func unitFiles(src *ledger.Source, units []ledger.Unit, rep *ingestcore.Report, command string) (map[string][]byte, error) {
	var gz bytes.Buffer
	if err := ledger.EncodeUnits(&gz, units); err != nil {
		return nil, err
	}
	rb, err := yamlBytes(rep, "# Generated by `go run ./ledger/cmd/ledger "+command+"`. Do not edit.\n")
	if err != nil {
		return nil, err
	}
	return map[string][]byte{src.Units: gz.Bytes(), ledger.DirReports + "/" + src.ID + ".yaml": rb}, nil
}

// writeOrCheck writes the generated files under dir, or with check requires the committed ones
// to equal them, the unit list compared after decompression (D4).
func writeOrCheck(dir string, files map[string][]byte, check bool, command string) error {
	var errs []error
	for _, rel := range sortedKeys(files) {
		p := filepath.Join(dir, filepath.FromSlash(rel))
		if !check {
			if err := os.WriteFile(p, files[rel], 0o644); err != nil {
				return err
			}
			continue
		}
		got, err := os.ReadFile(p)
		if err != nil {
			errs = append(errs, err)
			continue
		}
		want := files[rel]
		if filepath.Ext(rel) == ".gz" {
			if want, err = ledger.Gunzip(want); err == nil {
				got, err = ledger.Gunzip(got)
			}
			if err != nil {
				errs = append(errs, fmt.Errorf("%s: %w", rel, err))
				continue
			}
		}
		if !bytes.Equal(got, want) {
			errs = append(errs, fmt.Errorf("%s differs from the ingest tool's output; regenerate it with ledger %s", rel, command))
		}
	}
	return errors.Join(errs...)
}

func printReport(stdout io.Writer, rep *ingestcore.Report) {
	_, _ = fmt.Fprintf(stdout, "%s: %d records, %d units, %d role keys, %d duplicates, %d merged, %d joined units\n",
		rep.Source, rep.Records, rep.Units, rep.RoleKeys, rep.Duplicates, rep.Merged, rep.JoinedUnits)
}

func cmdIngestVLLMPerf(args []string, stdout io.Writer) error {
	fs := flags("ingest-vllm-perf")
	rows := fs.String("rows", "", "rows.jsonl printed by ledger/vllmperf/export.py")
	recipes := fs.String("recipes", "", "recipes.jsonl printed by ledger/vllmperf/export.py")
	check := fs.Bool("check", false, "require the committed files to equal the generated ones instead of writing them")
	if err := parse(fs, args, 1, "ingest-vllm-perf -rows R -recipes C [-check] DIR"); err != nil {
		return err
	}
	if *rows == "" || *recipes == "" {
		return usageError{"-rows and -recipes are required"}
	}
	dir := fs.Arg(0)
	src, err := lookupSource(dir, vllmperf.SourceID)
	if err != nil {
		return err
	}
	rf, err := os.Open(*rows)
	if err != nil {
		return err
	}
	defer func() { _ = rf.Close() }()
	cf, err := os.Open(*recipes)
	if err != nil {
		return err
	}
	defer func() { _ = cf.Close() }()
	in, err := vllmperf.ReadInput(rf, cf)
	if err != nil {
		return err
	}
	if err := vllmperf.CheckRevision(src, in); err != nil {
		return err
	}
	units, rep, err := vllmperf.Ingest(in, src.Revision.Ref)
	if err != nil {
		return err
	}
	files, err := unitFiles(src, units, rep, "ingest-vllm-perf")
	if err != nil {
		return err
	}
	if err := writeOrCheck(dir, files, *check, "ingest-vllm-perf"); err != nil {
		return err
	}
	printReport(stdout, rep)
	return nil
}

func cmdIngestSGLangNightly(args []string, stdout io.Writer) error {
	fs := flags("ingest-sglang-nightly")
	arts := fs.String("artifacts", "", "directory holding <artifact id>.zip for every artifact sources.yaml pins")
	check := fs.Bool("check", false, "require the committed files to equal the generated ones instead of writing them")
	if err := parse(fs, args, 1, "ingest-sglang-nightly -artifacts D [-check] DIR"); err != nil {
		return err
	}
	if *arts == "" {
		return usageError{"-artifacts is required"}
	}
	dir := fs.Arg(0)
	src, err := lookupSource(dir, sglangnightly.SourceID)
	if err != nil {
		return err
	}
	as, input, err := sglangnightly.ReadArtifacts(src, *arts)
	if err != nil {
		return err
	}
	units, rep, err := sglangnightly.Ingest(as, src.Revision.Ref, input)
	if err != nil {
		return err
	}
	files, err := unitFiles(src, units, rep, "ingest-sglang-nightly")
	if err != nil {
		return err
	}
	if err := writeOrCheck(dir, files, *check, "ingest-sglang-nightly"); err != nil {
		return err
	}
	printReport(stdout, rep)
	return nil
}

// cmdSGLangNightlyAssets prints one line per artifact the nightly source pins: the run, the
// attempt and the artifact's name and id, for the job that downloads them.
func cmdSGLangNightlyAssets(args []string, stdout io.Writer) error {
	fs := flags("sglang-nightly-assets")
	if err := parse(fs, args, 1, "sglang-nightly-assets DIR"); err != nil {
		return err
	}
	src, err := lookupSource(fs.Arg(0), sglangnightly.SourceID)
	if err != nil {
		return err
	}
	for _, a := range src.Artifacts {
		_, _ = fmt.Fprintf(stdout, "%s %d %s %s\n", a.Revision.Ref, a.Revision.RunAttempt, a.Revision.Artifact, a.ID)
	}
	return nil
}

func cmdIngestSGLangTraces(args []string, stdout io.Writer) error {
	fs := flags("ingest-sglang-traces")
	listing := fs.String("listing", "", "listing printed by ledger/sglangtraces/export.py")
	check := fs.Bool("check", false, "require the committed files to equal the generated ones instead of writing them")
	if err := parse(fs, args, 1, "ingest-sglang-traces -listing L [-check] DIR"); err != nil {
		return err
	}
	if *listing == "" {
		return usageError{"-listing is required"}
	}
	dir := fs.Arg(0)
	src, err := lookupSource(dir, sglangtraces.SourceID)
	if err != nil {
		return err
	}
	raw, err := os.ReadFile(*listing)
	if err != nil {
		return err
	}
	l, err := sglangtraces.ReadListing(bytes.NewReader(raw))
	if err != nil {
		return fmt.Errorf("%s: %w", *listing, err)
	}
	if err := sglangtraces.CheckRevision(src, l); err != nil {
		return err
	}
	units, rep, err := sglangtraces.Ingest(l, src.Revision.Ref, sha256Hex(raw))
	if err != nil {
		return err
	}
	files, err := unitFiles(src, units, rep, "ingest-sglang-traces")
	if err != nil {
		return err
	}
	if err := writeOrCheck(dir, files, *check, "ingest-sglang-traces"); err != nil {
		return err
	}
	printReport(stdout, rep)
	return nil
}

func sha256Hex(b []byte) string {
	s := sha256.Sum256(b)
	return hex.EncodeToString(s[:])
}
