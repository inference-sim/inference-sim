package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"strings"

	"github.com/inference-sim/inference-sim/substrate/ledger"
	"github.com/inference-sim/inference-sim/substrate/ledger/inferencex"
)

// urlList is a repeatable -url flag.
type urlList []string

func (u *urlList) String() string     { return strings.Join(*u, ",") }
func (u *urlList) Set(v string) error { *u = append(*u, v); return nil }

const (
	feedReportFile    = "feed-report.yaml"
	feedProposalsFile = "proposed-supplements.yaml"
)

// cmdFeed reconciles the API's feed with the pinned dump and writes, to -out, the ingest report
// and the supplements a ledger owner would pin. It changes nothing under LEDGER.
func cmdFeed(args []string, stdout io.Writer) error {
	fs := flags("feed")
	rowsPath := fs.String("rows", "", "rows printed by ledger/inferencex/export.sql")
	out := fs.String("out", "", "directory to write feed-report.yaml and proposed-supplements.yaml in")
	var urls urlList
	fs.Var(&urls, "url", "URL of the API that serves records (repeatable; needs the network)")
	if err := parse(fs, args, 1, "feed -rows R -url U [-url U...] -out DIR LEDGER"); err != nil {
		return err
	}
	if *rowsPath == "" || *out == "" || len(urls) == 0 {
		return usageError{"-rows, -out and at least one -url are required"}
	}
	sources, err := ledger.LoadSources(fs.Arg(0))
	if err != nil {
		return err
	}
	src := sources.Lookup(inferencex.SourceID)
	if src == nil {
		return fmt.Errorf("%s names no %q source", ledger.FileSources, inferencex.SourceID)
	}
	raw, err := os.ReadFile(*rowsPath)
	if err != nil {
		return err
	}
	sum := sha256.Sum256(raw)
	dump, err := inferencex.ReadRows(bytes.NewReader(raw))
	if err != nil {
		return fmt.Errorf("%s: %w", *rowsPath, err)
	}
	feed, err := inferencex.FetchFeed(urls, fetcher)
	if err != nil {
		return err
	}
	pinned, err := supplements(src)
	if err != nil {
		return err
	}
	pinnedIDs := map[int64]bool{}
	var pinnedRecs []inferencex.FeedRecord
	for i, d := range pinned {
		for _, r := range src.Supplements[i].Records {
			pinnedIDs[r.ID] = true
		}
		pinnedRecs = append(pinnedRecs, d.FeedRecords(src.Supplements[i])...)
	}
	if err := inferencex.MergePinned(feed, pinnedRecs); err != nil {
		return err
	}
	_, rep, err := inferencex.IngestWithFeed(dump, feed, src.Revision.Ref, hex.EncodeToString(sum[:]))
	if err != nil {
		return err
	}
	proposed := inferencex.ProposeSupplements(feed.Records, rep.Feed.Cutoff, pinnedIDs)
	repBytes, err := yamlBytes(rep, "# Generated by `go run ./ledger/cmd/ledger feed`. Ids and counts only; an input to a pull request, never committed.\n")
	if err != nil {
		return err
	}
	propBytes, err := yamlBytes(map[string]any{"supplements": proposed},
		"# Records the feed serves above the pinned dump that no supplement pins yet, by record id and content SHA-256 (D3).\n# A ledger owner reviews them and adds them under the inferencex source in sources.yaml.\n")
	if err != nil {
		return err
	}
	if err := os.MkdirAll(*out, 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(*out, feedReportFile), repBytes, 0o644); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(*out, feedProposalsFile), propBytes, 0o644); err != nil {
		return err
	}
	n := 0
	for _, s := range proposed {
		n += len(s.Records)
	}
	f := rep.Feed
	_, _ = fmt.Fprintf(stdout, "feed: cutoff %d, %d served, %d above the cutoff, %d owned by the dump (%d differ), %d straddling runs, %d records to pin in %d supplements\n",
		f.Cutoff, f.Served, f.APIRecords, f.OwnedByDump, len(f.RowDiffers), len(f.StraddlingRuns), n, len(proposed))
	return nil
}
