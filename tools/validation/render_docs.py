def c_kv(b: Build) -> dict:
    notes = b.named(b.anchors["C"]["records_file"]).parent / "NOTES.md"
    lines = notes.read_text().splitlines()
    try:
        i = next(k for k, ln in enumerate(lines) if ln.startswith("| arm | vLLM KV tokens"))
    except StopIteration:
        raise Fail(f"{notes}: no boot-time KV capacity table") from None
    out = {}
    for ln in lines[i + 2 :]:
        if not ln.startswith("|"):
            break
        cells = [c.strip() for c in ln.strip("|").split("|")]
        out[cells[0]] = float(cells[3])
    return out


