def stamp(builds: list[tuple[str, str]]) -> list[str]:
    """The admonition naming the BLIS binaries (version, sha256) a page describes."""
    out = ['!!! info "BLIS binaries these results describe"']
    out += [f"    - `{v}`, binary sha256 `{h}`" for v, h in builds]
    return out + [""]


def build_stamp(before: Build, after: Build) -> list[str]:
    bs = [before] if SINGLE else [before, after]
    return stamp([(f"(devel)+{b.full_commit}", b.binary_sha256) for b in bs])


def builds_line(before: Build, after: Build) -> str:
    if SINGLE:
        return f"Build: **{before.commit}**."
    return (
        f"Builds: **{before.commit}** (before) → **{after.commit}** (after); cells read "
        "`before → after`."
    )


def render(a) -> dict[str, str]:
    global SINGLE
    if (a.after is None) != (a.after_build is None):
        raise Fail("--after and --after-build go together")
    SINGLE = a.after is None
    if (a.after is None) != (a.after_binary is None):
        raise Fail("--after and --after-binary go together")
    before = Build(a.before.resolve(), a.before_build, a.before_binary)
    after = before if SINGLE else Build(a.after.resolve(), a.after_build, a.after_binary)
    prism = load(a.prism / "results.json")
    pages = {
        "index.md": page_index(before, after, prism, a.prism),
        "inferencex-agentic.md": page_inferencex_agentic(before, after),
        "inferencex-single-turn.md": page_inferencex_single_turn(before, after),
        "internal-deployments.md": page_internal(before, after),
        "llm-d-prism.md": page_prism(prism, after),
    }
    return {k: v.rstrip("\n") + "\n" for k, v in pages.items()}


def deny_check(pages: dict[str, str], patterns: pathlib.Path) -> None:
    pats = [
        ln.strip()
        for ln in patterns.read_text().splitlines()
        if ln.strip() and not ln.lstrip().startswith("#")
    ]
    rx = re.compile("|".join(f"(?:{p})" for p in pats), re.I)
    hits = [
        f"{name}:{i}: {ln}"
        for name, text in pages.items()
        for i, ln in enumerate(text.splitlines(), 1)
        if rx.search(ln)
    ]
    if hits:
        raise Fail("denied pattern in rendered pages:\n" + "\n".join(hits))


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--before", type=pathlib.Path, required=True)
    ap.add_argument("--before-build", required=True)
    ap.add_argument("--after", type=pathlib.Path)
    ap.add_argument("--before-binary", required=True, help="sha256 of the before BLIS binary")
    ap.add_argument("--after-build")
    ap.add_argument("--after-binary", help="sha256 of the after BLIS binary")
    ap.add_argument("--prism", type=pathlib.Path, required=True)
    ap.add_argument(
        "--out",
        type=pathlib.Path,
        default=pathlib.Path(__file__).resolve().parents[2] / "docs" / "validation",
    )
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--deny-patterns", type=pathlib.Path)
    a = ap.parse_args()
    try:
        pages = render(a)
        if a.deny_patterns:
            deny_check(pages, a.deny_patterns)
        if a.check:
            stale = [
                n
                for n, t in pages.items()
                if not (a.out / n).exists() or (a.out / n).read_text() != t
            ]
            if stale:
                raise Fail("out of date: " + ", ".join(stale))
            return
        a.out.mkdir(parents=True, exist_ok=True)
        for n, t in pages.items():
            (a.out / n).write_text(t)
    except Fail as e:
        sys.exit(f"render_docs: {e}")


if __name__ == "__main__":
    main()
