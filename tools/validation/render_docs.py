#!/usr/bin/env python3
"""Render docs/validation/ from the validation results JSON of two BLIS builds.

The inputs are the per-anchor results that the validation runs write (results.json and the
files it names by relative path and sha256), for a "before" and an "after" build, plus the
llm-d Prism results. They stay outside this repository: they hold measured values that are
not ours to redistribute. The pages carry only derived quantities (signed and absolute
errors, shape errors, ratios, counts of points and pairs), verdicts, mismatch lists, and
source citations by URL and commit. No measured value is written.

Usage (stdlib only):

    python -I tools/validation/render_docs.py \
        --before <results dir> --before-build <commit> --before-binary <sha256> \
        [--after <results dir> --after-build <commit> --after-binary <sha256>] \
        --prism <prism results dir> [--out docs/validation] [--check] \
        [--deny-patterns <file of regexes that must not appear in any page>]

Without --after, the pages show the before build alone.
--check renders into memory and fails if any page differs from the file on disk.
"""

