# ---------------------------------------------------------------- formatting


def pct(x: float | None) -> str:
    return "--" if x is None else f"{x:+.1f}%"


def mag(x: float | None) -> str:
    return "--" if x is None else f"{x:.1f}"


def rat(x: float | None) -> str:
    return "--" if x is None else f"{x:.2f}"


SINGLE = False


def ba(before: str, after: str) -> str:
    return after if SINGLE else f"{before} → {after}"


def table(header: list[str], rows: list[list[str]]) -> list[str]:
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return out + [""]


def sign_word(xs: list[float]) -> str:
    xs = [x for x in xs if x is not None]
    if not xs:
        return "--"
    over = sum(x > 0 for x in xs)
    if over == len(xs):
        return "BLIS high at every level"
    if over == 0:
        return "BLIS low at every level"
    return f"mixed ({over} high / {len(xs) - over} low)"


# ---------------------------------------------------------------- inputs


def sha(p: pathlib.Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def load(p: pathlib.Path):
    try:
        return json.loads(p.read_text())
    except FileNotFoundError:
        raise Fail(f"missing input {p}") from None


class Build:
    """One build's validation results: results.json plus the files it names."""

    def __init__(self, root: pathlib.Path, commit: str, binary_sha256: str):
        if not re.fullmatch(r"[0-9a-f]{7,40}", commit):
            raise Fail(f"build commit {commit!r} is not a hex commit")
        if not re.fullmatch(r"[0-9a-f]{64}", binary_sha256):
            raise Fail(f"binary sha256 {binary_sha256!r} is not 64 hex digits")
        self.root = root
        self.commit = commit[:8]
        self.full_commit = commit
        self.binary_sha256 = binary_sha256
        self.results_path = root / "results.json"
        self.results = load(self.results_path)
        self.anchors = self.results["anchors"]

    def named(self, ref: dict) -> pathlib.Path:
        p = self.root / ref["path"]
        if sha(p) != ref["sha256"]:
            raise Fail(f"{p}: sha256 differs from the one results.json records")
        return p


