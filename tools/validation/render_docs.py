ESTIMATOR_BLOCKS = [
    ("TPOT shape error", "tpot_shape"),
    ("TPOT mape", "tpot_mape"),
    ("TTFT shape error", "ttft_shape"),
    ("TTFT mape", "ttft_mape"),
]
TIERS = ["STRICT", "MEASURED-OR-RESOLVED", "ALL (approximate)"]


def parse_metricscore_tiers(text: str) -> dict:
    """{block: {tier: {estimator: (n, signed mean, mean|e|)}}} from metricscore's report."""
    out: dict = {}
    for title, key in ESTIMATOR_BLOCKS:
        m = re.search(r"^=== " + re.escape(title) + r".*?\n(.*?)(?:\n\n|\Z)", text, re.S | re.M)
        if not m:
            raise Fail(f"metricscore report has no '=== {title}' block")
        blk: dict = {}
        for line in m[1].splitlines()[1:]:
            tier = next((t for t in TIERS if line.startswith(t)), None)
            if tier is None:
                raise Fail(f"metricscore '{title}' row has no known tier: {line!r}")
            rest = line[len(tier) :].split()
            n_at = next(i for i, w in enumerate(rest) if w.isdigit())
            est, nums = " ".join(rest[:n_at]), rest[n_at:]
            n = int(nums[0])
            if n == 0:
                blk.setdefault(tier, {})[est] = (0, None, None)
                continue
            blk.setdefault(tier, {})[est] = (
                n,
                float(nums[1].rstrip("%")),
                float(nums[3].rstrip("%")),
            )
        out[key] = blk
    return out


