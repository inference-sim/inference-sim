def arm_label(key: str) -> str:
    m = re.fullmatch(r"(h\d+)-tp(\d+)-(\d\d)(\d\d)", key)
    if not m:
        raise Fail(f"unrecognised InferenceX arm key {key!r}")
    return f"{m[1].upper()} TP{m[2]} (run of {m[3]}-{m[4]})"


def a_arms(b: Build) -> dict:
    return b.anchors["A"]["arms"]


def pairs_by_c(rec: dict) -> dict:
    return {L["concurrency"]: L for L in rec["request_level_pairs"]["levels"]}


def pair_stat(L: dict | None, group: str, metric: str) -> tuple[float | None, int]:
    if not L:
        return None, 0
    s = (L.get(group) or {}).get(metric) or {}
    return s.get("median_pct"), s.get("n") or 0


def kv_ratio(level: dict) -> float | None:
    m = level["measured"].get("kv_cache_pool_tokens")
    p = level["blis"].get("kv_cache_pool_tokens")
    return p / m if m and p else None


def slope_ratio(rec: dict) -> float | None:
    fit = rec["itl_vs_inflight_fit"]
    m, p = fit["measured"]["slope_ms_per_inflight"], fit["blis"]["slope_ms_per_inflight"]
    return p / m if m else None


def primer_err(arm: dict) -> float | None:
    p = arm.get("primer_c1")
    if not p or not p.get("ttft_measured_ms"):
        return None
    return 100 * (p["ttft_blis_ms"] / p["ttft_measured_ms"] - 1)


def a_mismatches(rec: dict) -> tuple[list[dict], list[dict]]:
    rows = rec["config_diff"]
    hard = [r for r in rows if r["verdict"].startswith("MISMATCH")]
    soft = [r for r in rows if not r["verdict"].startswith("MISMATCH")]
    return hard, soft


