"""Print the freeze section for repos/cov/HARNESS.md from the published results (never typed by hand).

Usage: uv run --no-project python -I final_section.py > section.md
"""

import collections
import json
from pathlib import Path
import sys as _s
_s.path.insert(0, str(Path(__file__).resolve().parent))
import paths as PX  # noqa: E402

HERE = Path(__file__).resolve().parent
RES = PX.ROOT / "results"
WORK = PX.ROOT / "work"
SHOW = ["median_ttft_ms", "p50_ttft_ms", "median_tpot_ms", "p50_itl_ms", "p90_intvty", "median_intvty",
        "tput_per_gpu", "output_tput_tps", "gpu_cache_hit_rate_whole_run", "kv_cache_pool_tokens"]


def fmt(e):
    if not e:
        return "-"
    return f"{e['mape']:.1f} [{e['mape_ci95'][0]:.1f}, {e['mape_ci95'][1]:.1f}] ({e['signed_median']:+.1f}; n={e['n']}, runs={e['runs']})"


def main():
    plan = [json.loads(ln) for ln in (WORK / "plan.jsonl").open()]
    st = collections.Counter()
    blk = collections.Counter()
    for x in plan:
        f = WORK / "points" / x["run_id"] / f"c{x['conc']}_{x['point_id']}" / "result.json"
        if not f.exists():
            st[(x["set"], "not reached")] += 1
            continue
        r = json.loads(f.read_text())
        s = r["status"] if r["status"] != "error" else "error (stale, pending re-run)"
        st[(x["set"], s)] += 1
        if r["status"] == "blocked":
            reason = r["blocked_reason"]
            for key in ("eagle3", "70b recipe", "P/D or multinode", "per-", "cpu_offload_gb", "not simulated", "no catalog model",
                        "max_model_len unstated", "unbound variable", "CALCULATED_MAX_MODEL_LEN"):
                if key in reason:
                    reason = {"eagle3": "eagle3 drafter (catalog graph states an MTP speculator)",
                              "70b recipe": "llama70b: served nvidia/Llama-3.3-70B-Instruct-FP8/FP4, no catalog entry, no log",
                              "P/D or multinode": "P/D or multinode serving",
                              "per-": "BLIS startup refusal (KV pool cannot hold max_model_len)",
                              "cpu_offload_gb": "UVA weight offload (cpu_offload_gb)",
                              "not simulated": "KV connector not simulated (SimpleCPUOffload/LMCache/Mooncake)",
                              "no catalog model": "served checkpoint not in catalog",
                              "max_model_len unstated": "max_model_len unstated (no log, no recipe)",
                              "unbound variable": "recipe flag with unbound variable",
                              "CALCULATED_MAX_MODEL_LEN": "recipe max-model-len fallback unrecorded"}[key]
                    break
            blk[(x["set"], reason[:110])] += 1
    rep = json.loads((RES / "heldout" / "heldout_report.json").read_text())
    print("\n## FREEZE (2026-10-17 05:40): points, held-out error, blockers")
    print("Generated by validation/coverage/harness/final_section.py from results/ (no hand-typed numbers).\n")
    print("| set | status | points |\n|---|---|---|")
    for (s, k), v in sorted(st.items()):
        print(f"| {s} | {k} | {v} |")
    print(f"\nHeld-out sample: {rep['statement']}.")
    print("Error cell = post-stratified MAPE % [95% CI, run-clustered bootstrap within strata] (signed median %; n points, runs).")
    for m in ("median_tpot_ms", "p50_itl_ms"):
        one = rep["resolved_builds"]["metrics"].get(m)
        if one:
            print(f"Strata with a single scored run, {m} (no within-stratum variance; CI optimistic there): "
                  f"{one['strata_single_run']} of {one['strata']}.")
    print("Single-turn rows carry median_*/tpot (vllm bench); agentic rows carry p50_*/itl (aiperf): the two metric families "
          "are separate rows by definition.\n")
    print("| metric | resolved builds | unresolvable builds | DSV4.1 anchors (HELD) |\n|---|---|---|---|")
    for m in SHOW:
        print(f"| {m} | {fmt(rep['resolved_builds']['metrics'].get(m))} | {fmt(rep['unresolvable_builds']['metrics'].get(m))} | "
              f"{fmt(rep['dsv41_anchors']['metrics'].get(m))} |")
    print("\nPer-factor held-out error (resolved builds; levels with n >= 10; others are counts only):")
    for fk, lv in rep["by_factor"].items():
        print(f"\n{fk}:\n\n| level | n | TTFT med | TPOT/ITL med | p90 intvty | tput |\n|---|---|---|---|---|---|")
        for k, v in lv.items():
            if "metrics" not in v:
                print(f"| {k} | {v['n']} | (n<10) | | | |")
                continue
            mm = v["metrics"]
            tt = mm.get("median_ttft_ms") or mm.get("p50_ttft_ms")
            it = mm.get("median_tpot_ms") or mm.get("p50_itl_ms")
            iv = mm.get("p90_intvty") or mm.get("median_intvty")
            tp = mm.get("tput_per_gpu") or mm.get("output_tput_tps")
            short = lambda e: "-" if not e else f"{e['mape']:.1f} ({e['signed_median']:+.1f})"
            print(f"| {k} | {v['n']} | {short(tt)} | {short(it)} | {short(iv)} | {short(tp)} |")
    print("\nTop blockers by points:\n\n| set | reason | points |\n|---|---|---|")
    for (s, k), v in blk.most_common(20):
        print(f"| {s} | {k} | {v} |")


if __name__ == "__main__":
    main()
