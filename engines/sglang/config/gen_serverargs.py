"""Write config/serverargs_gen.go: SGLang's ServerArgs as a Go struct, field for field.

Every field fields/declarations.json lists under server_args (fields/gen_fields.py reads them from
SGLang's own declarations, python/sglang/srt/arg_groups/fields/*.py) becomes one field of the Go
struct ServerArgs, with:
  - its SGLang name, which is the only name a user configures it by (X1);
  - a Go type read from the declared Python type (GO_TYPES below);
  - its declared default in Defaults(), the value SGLang's ServerArgs(...) holds before
    resolution runs;
  - the site of its declaration, so the next release can be compared field by field.

The defaults are SGLang's, read from its declarations, not chosen here (X19): a default is a JSON
literal of fields/declarations.json, or one of the default expressions DEFAULT_EXPRS names. A
declaration whose type or default expression the generator does not know stops it, so a new
field shape in a later release is a decision for a person, not a silent guess.

Usage:
    python3 -I config/gen_serverargs.py fields/declarations.json > config/serverargs_gen.go
    python3 -I config/gen_serverargs.py fields/declarations.json --check config/serverargs_gen.go
"""
import json
import re
import sys

COMMIT = "297e54fd105e974cdf401e5b4d20253a22c16f90"
RELEASE = "v0.5.23"

# Python declared type -> Go type. Optional scalars are pointers (nil is None); lists are slices
# (nil is None, an empty slice is []). A type holding a dictionary, a union or a callable is a
# JSON value (any): config/ reads none of them, and a user's value is carried as given.
SCALARS = {"bool": "bool", "int": "int", "float": "float64", "str": "string"}
LISTS = {"List[str]": "[]string", "Optional[List[str]]": "[]string",
         "Optional[List[int]]": "[]int", "Optional[List[float]]": "[]float64"}
JSON_VALUE = re.compile(r"(Dict|dict|Union|Any|Callable|type\b)")

# A default given as an expression rather than a literal, and the Go it stands for.
DEFAULT_EXPRS = {
    "msgspec.field(default_factory=list)": "[]string{}",
    "1024 * 1024": "1024 * 1024",
    "10 * 1000 * 1000": "10 * 1000 * 1000",
}


def go_type(t: str) -> str:
    if t in SCALARS:
        return SCALARS[t]
    if t in LISTS:
        return LISTS[t]
    if t == "Optional[CudaGraphConfig]":
        return "*CudaGraphConfig"
    m = re.fullmatch(r"Optional\[(bool|int|float|str)\]", t)
    if m:
        return "*" + SCALARS[m.group(1)]
    m = re.fullmatch(r"Optional\[Literal\[(.*)\]\]", t) or re.fullmatch(r"()Literal\[(.*)\]", t)
    if m and not JSON_VALUE.search(t):
        opts = [o.strip() for o in m.groups()[-1].split(",")]
        optional = t.startswith("Optional[") or "None" in opts
        opts = [o for o in opts if o != "None"]
        if all(re.fullmatch(r"'[^']*'", o) for o in opts):
            return ("*" if optional else "") + "string"
        if all(re.fullmatch(r"-?\d+", o) for o in opts):
            return ("*" if optional else "") + "int"
    if JSON_VALUE.search(t):
        return "any"
    raise SystemExit(f"gen_serverargs: no Go type for the declared type {t!r}")


def camel(name: str) -> str:
    return "".join(p[:1].upper() + p[1:] for p in name.split("_") if p)


def go_literal(gt: str, v, name: str) -> str:
    """The Go expression for a declared JSON default, or "" for Go's zero value."""
    if v is None:
        return ""
    base = gt.lstrip("*")
    if base == "bool":
        lit = "true" if v else ""
        if gt.startswith("*"):
            return f"ptr({'true' if v else 'false'})"
        return lit
    if base in ("int", "float64"):
        if base == "int" and not (isinstance(v, int) and not isinstance(v, bool)):
            raise SystemExit(f"gen_serverargs: {name}: default {v!r} is not an int")
        lit = repr(v) if base == "int" else repr(float(v))
        if gt.startswith("*"):
            return f"ptr({base}({lit}))"
        return "" if v == 0 else lit
    if base == "string":
        lit = json.dumps(v)
        if gt.startswith("*"):
            return f"ptr({lit})"
        return "" if v == "" else lit
    if gt.startswith("[]") and isinstance(v, list):
        elem = gt[2:]
        return gt + "{" + ", ".join(go_literal(elem, x, name) or "0" for x in v) + "}"
    raise SystemExit(f"gen_serverargs: {name}: no Go literal for default {v!r} of {gt}")


def render(decl: dict) -> str:
    sa = decl["server_args"]
    files = sorted({d["site"].rsplit(":", 1)[0] for d in sa.values()})
    out = ["// SPDX-License-Identifier: Apache-2.0",
           "// SPDX-FileCopyrightText: Copyright 2023-2024 SGLang Team"]
    out += [f"// Derived from {f} at SGLang {RELEASE} ({COMMIT})." for f in files]
    out += ["//",
            "// Code generated by config/gen_serverargs.py from fields/declarations.json; DO NOT EDIT.",
            "",
            "package config",
            "",
            "// ServerArgs is SGLang's ServerArgs, one Go field for each field its declarations state",
            "// (python/sglang/srt/server_args.py collects them from arg_groups/fields/*.py). A nil",
            "// pointer or slice is Python's None.",
            "type ServerArgs struct {"]
    names = sorted(sa)
    types = {n: go_type(sa[n]["type"]) for n in names}
    for n in names:
        out.append(f"\t// {camel(n)} is {n} ({sa[n]['type']}), declared at {sa[n]['site']}.")
        out.append(f"\t{camel(n)} {types[n]}")
    out += ["}", "",
            "// Defaults is ServerArgs as SGLang declares it, before resolution runs. A field not",
            "// named here defaults to Go's zero value, which is its declared default.",
            "func Defaults() ServerArgs {",
            "\treturn ServerArgs{"]
    entries = []
    for n in names:
        d = sa[n]
        if "default_expr" in d:
            if d["default_expr"] not in DEFAULT_EXPRS:
                raise SystemExit(f"gen_serverargs: {n}: unknown default expression {d['default_expr']!r}")
            lit = DEFAULT_EXPRS[d["default_expr"]]
            if lit == "[]string{}" and types[n] != "[]string":
                raise SystemExit(f"gen_serverargs: {n}: list default for {types[n]}")
        elif "default" in d:
            lit = go_literal(types[n], d["default"], n)
        elif d.get("required"):
            lit = ""
        else:
            raise SystemExit(f"gen_serverargs: {n}: declares no default")
        if lit:
            entries.append((camel(n) + ":", lit))
    width = max(len(k) for k, _ in entries)
    out += [f"\t\t{k:<{width}} {v}," for k, v in entries]
    out += ["\t}", "}", "",
            "// fieldTable names every field by its SGLang name, with a pointer to it in a ServerArgs.",
            "var fieldTable = []fieldRef{"]
    for n in names:
        out.append(f"\t{{{json.dumps(n)}, {json.dumps(sa[n]['site'])}, func(s *ServerArgs) any {{ return &s.{camel(n)} }}}},")
    out += ["}", ""]
    return "\n".join(out)


def main(argv) -> int:
    if len(argv) not in (1, 3) or (len(argv) == 3 and argv[1] != "--check"):
        print(__doc__.split("Usage:", 1)[1].strip(), file=sys.stderr)
        return 2
    with open(argv[0]) as f:
        text = render(json.load(f))
    if len(argv) == 3:
        with open(argv[2]) as f:
            if f.read() != text:
                print(f"{argv[2]} is not what config/gen_serverargs.py writes from {argv[0]}; regenerate it",
                      file=sys.stderr)
                return 1
        return 0
    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
