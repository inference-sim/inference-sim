# Original to blis-vllm.
"""Write surface.json: every feature vLLM registers at the pinned commit, each with one status.

The ITEMS come from vLLM's own registration tables at the pinned commit, read with the ast module
(vLLM is not imported), so a feature a new release registers appears in the list without anyone
adding it (design X9, §7.5, VLM-4). The STATUS of each item, with its evidence, issue or reason,
comes from tools/surface/status.json, which people edit. The generator refuses to write a list in
which an item has no status, a status names an item vLLM does not register, or a status lacks
what X9 asks of it, so the list is complete by construction and cannot carry a stale entry.

Usage:
    python3 -I tools/surface/gen_surface.py <vllm-source> tools/surface/status.json > surface.json
    python3 -I tools/surface/gen_surface.py <vllm-source> tools/surface/status.json --check surface.json
    python3 -I tools/surface/gen_surface.py <vllm-source> --items     (the derived item ids, one per line)

The working directory is the blis-vllm checkout: evidence paths and docs/metrics-manifest.json
are read from it (--repo names another).

The release is the one provenance.go's Upstream record names unless --upstream-tag and
--upstream-commit name another; a vLLM checkout at another commit is refused. Moving the build to a
new release changes provenance.go and status.json, and the list is regenerated by the same command.

What is read, by category (each item's "site" is the file and line it was read at):
  connector            every KVConnectorFactory.register_connector call in
                       vllm/distributed/kv_transfer/kv_connector/factory.py. A name whose class is
                       another registered name's class (NixlConnector = NixlPullConnector) is
                       recorded with alias_of, the class's own name.
  offload_spec         every OffloadingSpecFactory.register_spec call (vllm/v1/kv_offload/factory.py).
  secondary_tier       every SecondaryTierFactory.register_tier call (vllm/v1/kv_offload/tiering/factory.py).
  cache_policy         every CachePolicyFactory.register_cache_policy call
                       (vllm/v1/kv_offload/cpu/policies/factory.py).
  backpressure_class   every class of vllm/v1/kv_offload/tiering/backpressure.py that is not an
                       abstract base: the short names _import_class resolves in that module.
  offload_medium       the members of Medium (vllm/v1/kv_offload/base.py).
  offload_backend      the KVOffloadingBackend literal (vllm/config/cache.py) and the
                       SimpleCPUOffloadConnector's VALID_KV_OFFLOAD_BACKENDS.
  kv_event_publisher   the keys of EventPublisherFactory._registry (vllm/distributed/kv_events.py).
  kv_event_type        every subclass of KVCacheEvent in vllm/distributed/kv_events.py.
  kv_event_source      every subclass of KVConnectorKVEvents anywhere under vllm/.
  kv_cache_spec        every KVCacheSpecRegistry.register and register_role_manager call in
                       register_all_kvcache_specs (vllm/v1/core/single_type_kv_cache_manager.py),
                       with the manager each maps to. CUDA's register_custom_kv_cache_specs is the
                       platform base's, which registers nothing; a platform that overrides it fails
                       the generator.
  speculative_method   the SpeculativeMethod literal (vllm/config/speculative.py), with the literals
                       it names expanded. An MTPModelTypes name other than "mtp" is recorded with
                       alias_of "mtp", since SpeculativeConfig rewrites it to mtp.
  scheduler_policy     the SchedulerPolicy literal (vllm/config/scheduler.py).
  path_loader          each place vLLM loads a class by a module path or dotted name a setting
                       holds, found by its import call in the file that makes it.
  framework            each abstract class, with an abstract method, that the shared KV frameworks
                       define (§7.6): the connector base (split into its worker-side and
                       scheduler-side methods, at the base class's own section comments), the
                       offloading manager, spec and worker, the CPU tier's cache policy, the
                       tiering layer's parent and secondary-tier managers, and the backpressure
                       policy and detector.
  metric_family        every family of docs/metrics-manifest.json, which cmd/metricsmanifest
                       generates from every Prometheus constructor in the pinned source and CI checks
                       current in the same job.

Statuses (X9). Each status.json entry is keyed by item id ("<category>:<name>") and holds:
  modelled       "evidence": repository paths that exist, at least one an oracle scenario or a
                 golden trace (under oracle/scenarios*/ or a testdata/golden* directory). A
                 framework item also needs "recorded" and "direct": the recorded and direct traces
                 taken at its interface (FID-5), each a list of repository paths that exist.
  refused        "issue": the blis-vllm issue that models it. "refusal": the reason code the
                 engine's refusal carries, when it has one (code_not_visible for code BLIS does
                 not have, design §11.4).
  out_of_scope   "reason": hardware, no_priced_work or deprecated (§7.5), and "citation": the
                 upstream code that shows it, as vllm/<path>:<lines>@<commit8> of the release.
An alias carries its own entry, so its status is stated, never inherited.
"""

