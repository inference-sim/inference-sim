def publishers(src):
    for c in classes(parse(src, KV_EVENTS)):
        if c.name != "EventPublisherFactory":
            continue
        for s in c.body:
            if isinstance(s, ast.AnnAssign) and isinstance(s.target, ast.Name) and s.target.id == "_registry":
                return [item("kv_event_publisher", const_str(k), KV_EVENTS, k.lineno) for k in s.value.keys]
    raise GenError("%s: no EventPublisherFactory._registry" % KV_EVENTS)


def event_types(src):
    return [item("kv_event_type", c.name, KV_EVENTS, c.lineno)
            for c in classes(parse(src, KV_EVENTS)) if "KVCacheEvent" in base_names(c)]


def event_sources(src):
    out = []
    for root, dirs, files in os.walk(os.path.join(src, "vllm")):
        dirs.sort()
        for fn in sorted(files):
            if not fn.endswith(".py"):
                continue
            rel = os.path.relpath(os.path.join(root, fn), src).replace(os.sep, "/")
            text = read(src, rel)
            if "KVConnectorKVEvents)" not in text:
                continue
            for c in classes(ast.parse(text, filename=rel)):
                if "KVConnectorKVEvents" in base_names(c):
                    out.append(item("kv_event_source", c.name, rel, c.lineno))
    if not out:
        raise GenError("no KVConnectorKVEvents subclass under vllm/")
    return out


def kv_cache_specs(src):
    tree = parse(src, KV_SPECS)
    fn = [s for s in tree.body if isinstance(s, ast.FunctionDef) and s.name == "register_all_kvcache_specs"]
    if not fn:
        raise GenError("%s: no register_all_kvcache_specs" % KV_SPECS)
    out = []
    for node in ast.walk(fn[0]):
        if not isinstance(node, ast.Call) or not isinstance(node.func, ast.Attribute):
            continue
        f = node.func
        if isinstance(f.value, ast.Name) and f.value.id == "KVCacheSpecRegistry":
            a = [x.id if isinstance(x, ast.Name) else (x.attr if isinstance(x, ast.Attribute) else None) for x in node.args]
            if f.attr == "register":
                out.append(item("kv_cache_spec", a[0], KV_SPECS, node.lineno, manager=a[1]))
            elif f.attr == "register_role_manager":
                out.append(item("kv_cache_spec", "role " + a[0], KV_SPECS, node.lineno, manager=a[1]))
            else:
                raise GenError("%s:%d: KVCacheSpecRegistry.%s is not read" % (KV_SPECS, node.lineno, f.attr))
    # The platform hook the function ends with registers nothing on CUDA.
    cuda = read(src, "vllm/platforms/cuda.py")
    if "def register_custom_kv_cache_specs" in cuda:
        raise GenError("vllm/platforms/cuda.py overrides register_custom_kv_cache_specs: read what it registers")
    out.sort(key=lambda i: int(i["site"].rsplit(":", 1)[1]))
    return out


def speculative_methods(src):
    rel = "vllm/config/speculative.py"
    out = []
    for v, alias, line in literal_values(src, rel, "SpeculativeMethod"):
        extra = {}
        if alias == "MTPModelTypes" and v != "mtp":
            extra["alias_of"] = "mtp"
        out.append(item("speculative_method", v, rel, line, **extra))
    names = [i["name"] for i in out]
    if len(set(names)) != len(names):
        raise GenError("%s: SpeculativeMethod names a value twice" % rel)
    return out


def scheduler_policies(src):
    rel = "vllm/config/scheduler.py"
    return [item("scheduler_policy", v, rel, line) for v, _, line in literal_values(src, rel, "SchedulerPolicy")]


def registry_loads(src, rel):
    """The lines of rel that load a registered name's module: the import inside a register_*
    method's lazy loader."""
    out = set()
    for node in ast.walk(parse(src, rel)):
        if isinstance(node, ast.FunctionDef) and node.name.startswith("register_"):
            for inner in ast.walk(node):
                if isinstance(inner, ast.FunctionDef) and inner.name == "loader":
                    out.update(range(inner.lineno, inner.end_lineno + 1))
    return out


def path_loaders(src):
    out = []
    for name, rel, call, start in PATH_LOADERS:
        s = line_of(src, rel, start)
        out.append(item("path_loader", name, rel, line_of(src, rel, call, s)))
    known = {i["site"] for i in out}
    for top in KV_LOAD_SCAN:
        files = [top] if top.endswith(".py") else sorted(
            os.path.relpath(os.path.join(r, f), src).replace(os.sep, "/")
            for r, _, fs in os.walk(os.path.join(src, top)) for f in fs if f.endswith(".py"))
        for rel in files:
            text = read(src, rel)
            if not LOAD_CALL.search(text):
                continue
            lazy = registry_loads(src, rel)
            for i, l in enumerate(text.splitlines(), 1):
                if LOAD_CALL.search(l) and not l.lstrip().startswith(("#", "def ")) \
                        and site(rel, i) not in known and i not in lazy:
                    raise GenError("%s:%d loads a module by a name a setting can give, and no path_loader "
                                   "entry (PATH_LOADERS) accounts for it" % (rel, i))
    return out


def frameworks(src):
    out = []
    for rel in FRAMEWORK_FILES:
        lines = read(src, rel).splitlines()
        for c in classes(ast.parse("\n".join(lines), filename=rel)):
            if "ABC" not in base_names(c) or not is_abstract(c):
                continue
            if c.name != "KVConnectorBase_V1":
                out.append(item("framework", c.name, rel, c.lineno))
                continue
            for side in ("Worker-side methods", "Scheduler-side methods"):
                at = [i for i in range(c.lineno, c.end_lineno + 1) if lines[i - 1].strip() == "# " + side]
                if len(at) != 1:
                    raise GenError("%s: KVConnectorBase_V1 has no single %r section" % (rel, side))
                out.append(item("framework", "KVConnectorBase_V1 " + side.split("-")[0].lower() + " side", rel, at[0]))
    return out


def metric_families(repo):
    path = os.path.join(repo, "docs/metrics-manifest.json")
    try:
        with open(path, encoding="utf-8") as f:
            man = json.load(f)
    except (OSError, ValueError) as e:
        raise GenError("docs/metrics-manifest.json: %s" % e)
    if man.get("vllm") != UPSTREAM["tag"].lstrip("v"):
        raise GenError("docs/metrics-manifest.json is for vLLM %s, not %s" % (man.get("vllm"), UPSTREAM["tag"]))
    out = []
    for fam in man["families"]:
        rel, line = fam["defined"].rsplit(":", 1)
        out.append(item("metric_family", fam["name"], rel, int(line), manifest_class=fam["class"]))
    return out


def derive(src, repo):
    its = []
    its += connectors(src)
    its += simple_registry(src, SPEC_FACTORY, "OffloadingSpecFactory", "register_spec", "offload_spec")
    its += simple_registry(src, TIER_FACTORY, "SecondaryTierFactory", "register_tier", "secondary_tier")
    its += simple_registry(src, POLICY_FACTORY, "CachePolicyFactory", "register_cache_policy", "cache_policy")
    its += backpressure_classes(src)
    its += enum_members(src, OFFLOAD_BASE, "Medium", "offload_medium")
    its += offload_backends(src)
    its += publishers(src)
    its += event_types(src)
    its += event_sources(src)
    its += kv_cache_specs(src)
    its += speculative_methods(src)
    its += scheduler_policies(src)
    its += path_loaders(src)
    its += frameworks(src)
    its += metric_families(repo)
    ids = [i["id"] for i in its]
    dup = sorted({i for i in ids if ids.count(i) > 1})
    if dup:
        raise GenError("item ids derived twice: %s" % dup)
    return its


def paths_exist(repo, paths, what, errs):
    if not isinstance(paths, list) or not paths or not all(isinstance(p, str) and p for p in paths):
        errs.append("%s: want a non-empty list of repository paths" % what)
        return False
    for p in paths:
        if p.startswith("/") or ".." in p.split("/") or not os.path.exists(os.path.join(repo, p)):
            errs.append("%s: %s is not a path in this repository" % (what, p))
    return True


def check_entry(repo, it, st, errs):
    """X9's demands on one item's status entry, and FID-5's on a framework's."""
    iid = it["id"]
    status = st.get("status")
    if status not in STATUSES:
        errs.append("%s: status %r is not one of %s" % (iid, status, ", ".join(STATUSES)))
        return
    allowed = {"status", "why"}
    if status == "modelled":
        allowed |= {"evidence", "recorded", "direct"}
        if paths_exist(repo, st.get("evidence"), iid + ": evidence", errs) and \
                not any(SCENARIO.match(p) for p in st["evidence"]):
            errs.append("%s: modelled, but its evidence names no oracle scenario or golden trace" % iid)
        if it["category"] == "framework":
            for k in ("recorded", "direct"):
                if k not in st:
                    errs.append("%s: a framework is modelled only with %s traces at its interface (FID-5)" % (iid, k))
                else:
                    paths_exist(repo, st[k], "%s: %s" % (iid, k), errs)
        else:
            for k in ("recorded", "direct"):
                if k in st:
                    errs.append("%s: %s traces are a framework's (FID-5); this is a %s" % (iid, k, it["category"]))
    elif status == "refused":
        allowed |= {"issue", "refusal"}
        if not ISSUE.match(str(st.get("issue", ""))):
            errs.append("%s: refused, but issue %r is not a blis-vllm issue URL" % (iid, st.get("issue")))
        if "refusal" in st and st["refusal"] not in REFUSALS:
            errs.append("%s: refusal %r is not one of %s" % (iid, st["refusal"], ", ".join(REFUSALS)))
    else:
        allowed |= {"reason", "citation"}
        if st.get("reason") not in REASONS:
            errs.append("%s: out_of_scope reason %r is not one of %s (§7.5)" % (iid, st.get("reason"), ", ".join(REASONS)))
        if not citation_rule().match(str(st.get("citation", ""))):
            errs.append("%s: out_of_scope citation %r is not vllm/<path>:<lines>@%s" % (iid, st.get("citation"), UPSTREAM["commit"][:8]))
    extra = sorted(set(st) - allowed)
    if extra:
        errs.append("%s: keys %s do not belong with status %s" % (iid, extra, status))


def build(src, status, repo):
    its = derive(src, repo)
    entries = status.get("items", {})
    errs = []
    known = {i["id"] for i in its}
    for k in sorted(set(entries) - known):
        errs.append("%s: has a status but vLLM %s registers no such item" % (k, UPSTREAM["tag"]))
    out = []
    for it in its:
        st = entries.get(it["id"])
        if st is None:
            errs.append("%s: no status (%s); add it to tools/surface/status.json" % (it["id"], it["site"]))
            continue
        check_entry(repo, it, st, errs)
        row = dict(it)
        row.update(st)
        out.append(row)
    if errs:
        raise GenError("\n".join(errs))
    counts = {}
    for r in out:
        counts[r["status"]] = counts.get(r["status"], 0) + 1
    return {
        "generator": "tools/surface/gen_surface.py",
        "upstream": {"name": "vllm", "tag": UPSTREAM["tag"], "commit": UPSTREAM["commit"]},
        "counts": dict(sorted(counts.items())),
        "items": out,
    }


def render(doc):
    return json.dumps(doc, indent=1, ensure_ascii=False) + "\n"


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("vllm_source")
    ap.add_argument("status", nargs="?")
    ap.add_argument("--check", metavar="SURFACE_JSON")
    ap.add_argument("--repo", default=".", help="the blis-vllm checkout (default: the working directory)")
    ap.add_argument("--items", action="store_true", help="print the derived item ids and exit")
    ap.add_argument("--upstream-tag", help="the vLLM release tag (default: provenance.go's Upstream.Tag)")
    ap.add_argument("--upstream-commit", help="its 40-hex commit (default: provenance.go's Upstream.Commit)")
    a = ap.parse_args(argv)
    try:
        if bool(a.upstream_tag) != bool(a.upstream_commit):
            raise GenError("--upstream-tag and --upstream-commit go together")
        tag, commit = (a.upstream_tag, a.upstream_commit) if a.upstream_tag else provenance_upstream(a.repo)
        if not re.fullmatch(r"[0-9a-f]{40}", commit):
            raise GenError("upstream commit %r is not 40 hex digits" % commit)
        head = checkout_commit(a.vllm_source)
        if head is not None and head != commit:
            raise GenError("the vLLM checkout is at %s, not %s (%s)" % (head, commit, tag))
        UPSTREAM["tag"], UPSTREAM["commit"] = tag, commit
        if a.items:
            for it in derive(a.vllm_source, a.repo):
                print(it["id"], it["site"])
            return 0
        if a.status is None:
            ap.error("status.json is required")
        with open(a.status, encoding="utf-8") as f:
            status = json.load(f)
        out = render(build(a.vllm_source, status, a.repo))
    except GenError as e:
        print("gen_surface: " + str(e).replace("\n", "\ngen_surface: "), file=sys.stderr)
        return 1
    if a.check:
        try:
            with open(a.check, encoding="utf-8") as f:
                have = f.read()
        except OSError as e:
            print("gen_surface: %s" % e, file=sys.stderr)
            return 1
        if have != out:
            sys.stdout.writelines(difflib.unified_diff(
                have.splitlines(True), out.splitlines(True), a.check, "generated"))
            print("gen_surface: %s is not what the generator writes; regenerate it" % a.check, file=sys.stderr)
            return 1
        return 0
    sys.stdout.write(out)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
