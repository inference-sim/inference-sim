def citation_rule():
    return re.compile(r"^vllm/[A-Za-z0-9_./-]+\.py:[0-9]+(-[0-9]+)?(, ?[0-9]+(-[0-9]+)?)*@" + UPSTREAM["commit"][:8] + "$")


def provenance_upstream(repo):
    """The Upstream record of provenance.go: its Tag and Commit."""
    path = os.path.join(repo, "provenance.go")
    try:
        with open(path, encoding="utf-8") as f:
            text = f.read()
    except OSError as e:
        raise GenError("provenance.go: %s" % e)
    m = re.search(r"var Upstream = UpstreamRelease\{(.*?)\n\}", text, re.S)
    tag = m and re.search(r'\bTag:\s*"([^"]+)"', m.group(1))
    commit = m and re.search(r'\bCommit:\s*"([0-9a-f]{40})"', m.group(1))
    if not (tag and commit):
        raise GenError("provenance.go: no Upstream record with a Tag and a 40-hex Commit")
    return tag.group(1), commit.group(1)


def checkout_commit(src):
    """The commit the vLLM checkout is at, or None when it is not a git checkout."""
    import subprocess
    try:
        r = subprocess.run(["git", "-C", src, "rev-parse", "HEAD"], capture_output=True, text=True, check=False)
    except OSError:
        return None
    if r.returncode != 0:
        return None
    top = subprocess.run(["git", "-C", src, "rev-parse", "--show-toplevel"], capture_output=True, text=True, check=False)
    # A directory inside some other checkout is not a vLLM checkout of its own.
    if top.returncode != 0 or os.path.realpath(top.stdout.strip()) != os.path.realpath(src):
        return None
    return r.stdout.strip()
