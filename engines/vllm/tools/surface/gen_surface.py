class GenError(Exception):
    pass


def read(src, rel):
    path = os.path.join(src, rel)
    try:
        with open(path, encoding="utf-8") as f:
            return f.read()
    except OSError as e:
        raise GenError("cannot read %s: %s" % (rel, e))


def parse(src, rel):
    return ast.parse(read(src, rel), filename=rel)


def site(rel, line):
    return "%s:%d" % (rel, line)


def const_str(node):
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return node.value
    return None


def register_calls(src, rel, owner, method):
    """Module-level owner.method(...) calls, as (line, [string args])."""
    out = []
    for stmt in parse(src, rel).body:
        if not isinstance(stmt, ast.Expr) or not isinstance(stmt.value, ast.Call):
            continue
        f = stmt.value.func
        if isinstance(f, ast.Attribute) and f.attr == method and isinstance(f.value, ast.Name) and f.value.id == owner:
            out.append((stmt.lineno, [const_str(a) for a in stmt.value.args]))
    if not out:
        raise GenError("%s: no %s.%s call" % (rel, owner, method))
    return out


def module_file(src, module):
    base = module.replace(".", "/")
    for cand in (base + ".py", base + "/__init__.py"):
        if os.path.isfile(os.path.join(src, cand)):
            return cand
    raise GenError("module %s is not in the source tree" % module)


def resolve_class(src, module, name, depth=0):
    """The (file, class name) a registered module and class name resolve to, following
    `from X import Name` and a top-level `Name = Other`."""
    if depth > 8:
        raise GenError("%s.%s: import chain too deep" % (module, name))
    rel = module_file(src, module)
    tree = parse(src, rel)
    for stmt in tree.body:
        if isinstance(stmt, ast.ClassDef) and stmt.name == name:
            return rel, name
    for stmt in tree.body:
        if isinstance(stmt, ast.Assign) and len(stmt.targets) == 1 and isinstance(stmt.targets[0], ast.Name) \
                and stmt.targets[0].id == name:
            if isinstance(stmt.value, ast.Name):
                return resolve_class(src, module, stmt.value.id, depth + 1)
            # Bound at import by a call (LMCacheMPConnector = _resolve_lmcache_mp_connector()): its
            # own class, shared with no other name.
            return rel, name
        if isinstance(stmt, ast.ImportFrom) and stmt.module:
            for a in stmt.names:
                if (a.asname or a.name) == name:
                    return resolve_class(src, stmt.module, a.name, depth + 1)
    raise GenError("%s: no class %s" % (rel, name))


def literal_values(src, rel, alias, seen=None):
    """The strings of a module-level `alias = Literal[...]`, with the literals it names expanded,
    each with the alias it came from."""
    seen = seen or set()
    if alias in seen:
        raise GenError("%s: %s is circular" % (rel, alias))
    seen.add(alias)
    tree = parse(src, rel)
    for stmt in tree.body:
        if isinstance(stmt, ast.Assign) and len(stmt.targets) == 1 and isinstance(stmt.targets[0], ast.Name) \
                and stmt.targets[0].id == alias:
            v = stmt.value
            if not (isinstance(v, ast.Subscript) and isinstance(v.value, ast.Name) and v.value.id == "Literal"):
                raise GenError("%s: %s is not a Literal" % (rel, alias))
            elts = v.slice.elts if isinstance(v.slice, ast.Tuple) else [v.slice]
            out = []
            for e in elts:
                s = const_str(e)
                if s is not None:
                    out.append((s, alias, stmt.lineno))
                elif isinstance(e, ast.Name):
                    out.extend(literal_values(src, rel, e.id, seen))
                else:
                    raise GenError("%s: %s holds %s" % (rel, alias, ast.dump(e)))
            return out
    raise GenError("%s: no %s" % (rel, alias))


def line_of(src, rel, pattern, start=1):
    rx = re.compile(pattern)
    for i, l in enumerate(read(src, rel).splitlines(), 1):
        if i >= start and rx.search(l):
            return i
    raise GenError("%s: no line matches %r" % (rel, pattern))


def classes(tree):
    return [s for s in tree.body if isinstance(s, ast.ClassDef)]


def base_names(c):
    out = []
    for b in c.bases:
        if isinstance(b, ast.Name):
            out.append(b.id)
        elif isinstance(b, ast.Attribute):
            out.append(b.attr)
    return out


def is_abstract(c):
    for d in ast.walk(c):
        if isinstance(d, (ast.FunctionDef, ast.AsyncFunctionDef)):
            for dec in d.decorator_list:
                if (isinstance(dec, ast.Name) and dec.id == "abstractmethod") or \
                        (isinstance(dec, ast.Attribute) and dec.attr == "abstractmethod"):
                    return True
    return False


def item(category, name, rel, line, **extra):
    d = {"id": "%s:%s" % (category, name), "category": category, "name": name, "site": site(rel, line)}
    d.update(extra)
    return d


def connectors(src):
    out, by_class = [], {}
    for line, args in register_calls(src, FACTORY, "KVConnectorFactory", "register_connector"):
        name, module, cls = args[:3]
        if None in (name, module, cls):
            raise GenError("%s:%d: a register_connector argument is not a literal" % (FACTORY, line))
        target = resolve_class(src, module, cls)
        it = item("connector", name, FACTORY, line, **{"class": "%s.%s" % (module, cls)})
        by_class.setdefault(target, []).append(it)
        out.append(it)
    for target, its in by_class.items():
        if len(its) < 2:
            continue
        own = [i for i in its if i["name"] == target[1]]
        if len(own) != 1:
            raise GenError("connectors %s share a class none of them is named for" % [i["name"] for i in its])
        for i in its:
            if i is not own[0]:
                i["alias_of"] = own[0]["name"]
    return out


def simple_registry(src, rel, owner, method, category):
    out = []
    for line, args in register_calls(src, rel, owner, method):
        name, module, cls = args[:3]
        if None in (name, module, cls):
            raise GenError("%s:%d: a %s argument is not a literal" % (rel, line, method))
        resolve_class(src, module, cls)
        out.append(item(category, name, rel, line, **{"class": "%s.%s" % (module, cls)}))
    return out


def backpressure_classes(src):
    tree = parse(src, BACKPRESSURE)
    return [item("backpressure_class", c.name, BACKPRESSURE, c.lineno)
            for c in classes(tree) if "ABC" not in base_names(c)]


def enum_members(src, rel, cls, category):
    for c in classes(parse(src, rel)):
        if c.name == cls:
            out = []
            for s in c.body:
                if isinstance(s, ast.Assign) and isinstance(s.targets[0], ast.Name):
                    out.append(item(category, s.targets[0].id, rel, s.lineno))
            return out
    raise GenError("%s: no class %s" % (rel, cls))


def tuple_values(src, rel, name):
    for stmt in parse(src, rel).body:
        if isinstance(stmt, ast.Assign) and isinstance(stmt.targets[0], ast.Name) and stmt.targets[0].id == name:
            if not isinstance(stmt.value, (ast.Tuple, ast.List)):
                raise GenError("%s: %s is not a tuple" % (rel, name))
            return [(const_str(e), stmt.lineno) for e in stmt.value.elts]
    raise GenError("%s: no %s" % (rel, name))


