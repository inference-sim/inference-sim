package cmd

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// The docs/validation/ pages are rendered by tools/validation/render_docs.py from results that
// stay outside the repository, so CI cannot regenerate them. These checks catch the edits
// that would silently detach a page from its generator or from the site.

const validationGeneratedMarker = "<!-- Generated by tools/validation/render_docs.py"

func TestValidationPagesAreGeneratedAndInNav(t *testing.T) {
	pages, err := filepath.Glob("../docs/validation/*.md")
	if err != nil {
		t.Fatal(err)
	}
	if len(pages) == 0 {
		t.Fatal("docs/validation/ has no pages")
	}
	nav, err := os.ReadFile("../mkdocs.yml")
	if err != nil {
		t.Fatal(err)
	}
	for _, p := range pages {
		src, err := os.ReadFile(p)
		if err != nil {
			t.Fatal(err)
		}
		if !strings.HasPrefix(string(src), validationGeneratedMarker) {
			t.Errorf("%s does not start with the generator's marker: edit render_docs.py and "+
				"re-run it instead of editing the page", p)
		}
		if !strings.Contains(string(nav), "validation/"+filepath.Base(p)) {
			t.Errorf("%s is not in the mkdocs.yml nav", p)
		}
	}
}

func TestLatencyGuidePointsAtValidationResults(t *testing.T) {
	body := docSection(t, "../docs/guide/latency-models.md", "The published accuracy figures")
	if !strings.Contains(body, "../validation/index.md") {
		t.Error("the published accuracy figures section must link ../validation/index.md")
	}
}
